#!/usr/bin/env bash
#
# Creates a GitHub release of SOURCE with the macOS builds (standalone app, Audio Unit and VST3, built here) and the
# Linux builds (standalone app, VST3 and LV2 for x86_64 and arm64, built by the "Linux release builds" GitHub Actions
# workflow when the release is published, see .github/workflows/linux-release.yml). Each build is in its own zip file.
#
# Usage:
#   ./make_release.sh [version] [--draft] [--prerelease] [--notes-file FILE] [--dry-run] [--no-wait]
#
#   version         Release version (default: the VERSION in CMakeLists.txt). The tag is "v<version>".
#   --draft         Create the release as a draft (not visible until published from GitHub)
#   --prerelease    Mark the release as a pre-release
#   --notes-file    Release notes (default: notes generated by GitHub from the commits since the last release)
#   --dry-run       Build and package, but don't create the release (the zip files are left in dist/)
#   --no-wait       Don't wait for the Linux builds (they are attached to the release when the workflow finishes)
#
# Requirements: the GitHub CLI (gh) logged in, a clean working tree and the current commit pushed (the tag is created
# by GitHub on that commit). Builds are Release builds (tests are run) and ad-hoc signed, not notarized: users have to
# allow them in System Settings > Privacy & Security the first time (or remove the quarantine attribute).
#
# Builds are universal (Apple Silicon and Intel, set ARCHITECTURES=arm64 for faster Apple Silicon only builds). Extra
# CMake arguments can be passed with CMAKE_ARGS (e.g. CMAKE_ARGS="-DSOURCE_FREESOUND_API_KEY=xxxx").

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$SCRIPT_DIR/build-release-universal}"
ARCHITECTURES="${ARCHITECTURES:-arm64;x86_64}"  # Universal binaries (Apple Silicon and Intel)
DIST_DIR="$SCRIPT_DIR/dist"

VERSION=""
DRAFT=0
PRERELEASE=0
DRY_RUN=0
WAIT=1
NOTES_FILE=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --draft)       DRAFT=1 ;;
        --prerelease)  PRERELEASE=1 ;;
        --dry-run)     DRY_RUN=1 ;;
        --no-wait)     WAIT=0 ;;
        --notes-file)  shift; NOTES_FILE="${1:-}" ;;
        -h|--help)     sed -n '2,25p' "$0"; exit 0 ;;
        -*)            echo "Unknown option: $1" >&2; exit 1 ;;
        *)             VERSION="${1#v}" ;;
    esac
    shift
done

if [[ "$(uname)" != "Darwin" ]]; then
    echo "Releases with macOS builds must be made on macOS" >&2
    exit 1
fi

CMAKE_VERSION=$(sed -n 's/^project(SourceSampler VERSION \([0-9.]*\).*/\1/p' "$SCRIPT_DIR/CMakeLists.txt")
VERSION="${VERSION:-$CMAKE_VERSION}"
TAG="v$VERSION"
if [[ "$VERSION" != "$CMAKE_VERSION" ]]; then
    echo "WARNING: release version $VERSION differs from the version in CMakeLists.txt ($CMAKE_VERSION), which is the" >&2
    echo "         version the plugins report to hosts. Consider updating CMakeLists.txt first." >&2
fi

# Checks (skipped in dry runs, except the tag)
cd "$REPO_DIR"
if [[ $DRY_RUN -eq 0 ]]; then
    command -v gh >/dev/null 2>&1 || { echo "The GitHub CLI (gh) is needed: brew install gh" >&2; exit 1; }
    gh auth status >/dev/null 2>&1 || { echo "Log in to GitHub first: gh auth login" >&2; exit 1; }
    if [[ -n "$(git status --porcelain --untracked-files=no)" ]]; then
        echo "The working tree has uncommitted changes: commit them first (the release is built from the current commit)" >&2
        exit 1
    fi
    git fetch --quiet origin
    if [[ -z "$(git branch -r --contains HEAD)" ]]; then
        echo "The current commit ($(git rev-parse --short HEAD)) is not pushed: push it first" >&2
        exit 1
    fi
fi
if git rev-parse -q --verify "refs/tags/$TAG" >/dev/null || git ls-remote --exit-code --tags origin "$TAG" >/dev/null 2>&1; then
    echo "Tag $TAG already exists" >&2
    exit 1
fi

# Build (Release, with tests) without installing
echo "==> Building SOURCE $VERSION"
CMAKE_ARGS="-DCMAKE_OSX_ARCHITECTURES=$ARCHITECTURES ${CMAKE_ARGS:-}" BUILD_DIR="$BUILD_DIR" "$SCRIPT_DIR/build_and_install.sh" --no-install

ARTEFACTS="$BUILD_DIR/SourceSampler_artefacts/Release"
APP="$ARTEFACTS/Standalone/SourceSampler.app"
AU="$ARTEFACTS/AU/SourceSampler.component"
VST3="$ARTEFACTS/VST3/SourceSampler.vst3"
for bundle in "$APP" "$AU" "$VST3"; do
    [[ -d "$bundle" ]] || { echo "Missing build: $bundle" >&2; exit 1; }
done

# Package: one zip per format (ad-hoc signed bundles)
echo "==> Packaging"
rm -rf "$DIST_DIR"
mkdir -p "$DIST_DIR"
ARCHS="$(lipo -archs "$APP/Contents/MacOS/SourceSampler")"
if [[ "$ARCHS" == *arm64* && "$ARCHS" == *x86_64* ]]; then ARCH="universal"; else ARCH="${ARCHS// /-}"; fi
package() {
    local bundle="$1" name="$2"
    local staging="$DIST_DIR/staging"
    rm -rf "$staging" && mkdir -p "$staging"
    cp -R "$bundle" "$staging/"
    codesign --force --deep --sign - "$staging/$(basename "$bundle")" >/dev/null 2>&1 || echo "    (warning: could not codesign $(basename "$bundle"))"
    local zip="$DIST_DIR/SOURCE-$VERSION-macOS-$ARCH-$name.zip"
    (cd "$staging" && ditto -c -k --sequesterRsrc --keepParent "$(basename "$bundle")" "$zip")
    rm -rf "$staging"
    echo "    $(basename "$zip")"
}
package "$APP" "Standalone"
package "$AU" "AU"
package "$VST3" "VST3"
(cd "$DIST_DIR" && shasum -a 256 ./*.zip | sed 's#\./##' > "SOURCE-$VERSION-macOS-SHA256.txt")

if [[ $DRY_RUN -eq 1 ]]; then
    echo "==> Dry run: release not created. Files in $DIST_DIR:"
    ls -1 "$DIST_DIR"
    exit 0
fi

# Release notes: given file, or generated by GitHub, plus installation instructions
NOTES="$DIST_DIR/notes.md"
{
    if [[ -n "$NOTES_FILE" ]]; then
        cat "$NOTES_FILE"
        echo
    fi
    cat <<EOF
### Installation

#### macOS

- **Standalone app**: unzip \`SourceSampler.app\` and move it to \`/Applications\`.
- **Audio Unit**: unzip \`SourceSampler.component\` into \`~/Library/Audio/Plug-Ins/Components\`.
- **VST3**: unzip \`SourceSampler.vst3\` into \`~/Library/Audio/Plug-Ins/VST3\`.

The builds are not notarized: the first time, allow them in *System Settings > Privacy & Security*, or remove the quarantine attribute, e.g. \`xattr -dr com.apple.quarantine ~/Library/Audio/Plug-Ins/Components/SourceSampler.component\`. Builds are $ARCH ($ARCHS).

#### Linux (x86_64 and arm64)

- **Standalone app**: unzip \`SourceSampler\` anywhere and run it (it uses ALSA or JACK).
- **VST3**: unzip \`SourceSampler.vst3\` into \`~/.vst3\`.
- **LV2**: unzip \`SourceSampler.lv2\` into \`~/.lv2\`.

Built on Ubuntu 22.04 (needs glibc 2.35 or newer, ALSA, libcurl, FreeType and X11 libraries).
EOF
} > "$NOTES"

RELEASE_ARGS=(--title "SOURCE $VERSION" --target "$(git rev-parse HEAD)" --notes-file "$NOTES")
[[ -z "$NOTES_FILE" ]] && RELEASE_ARGS+=(--generate-notes)
[[ $DRAFT -eq 1 ]] && RELEASE_ARGS+=(--draft)
[[ $PRERELEASE -eq 1 ]] && RELEASE_ARGS+=(--prerelease)

echo "==> Creating GitHub release $TAG"
gh release create "$TAG" "${RELEASE_ARGS[@]}" "$DIST_DIR"/*.zip "$DIST_DIR/SOURCE-$VERSION-macOS-SHA256.txt"

# Linux builds: the workflow starts when the release is published
if [[ $DRAFT -eq 1 ]]; then
    echo "==> Draft release: the Linux builds will be made and attached when it is published from GitHub"
elif [[ $WAIT -eq 1 ]]; then
    echo "==> Waiting for the Linux builds (GitHub Actions)"
    RUN_ID=""
    for _ in $(seq 1 30); do
        RUN_ID=$(gh run list --workflow linux-release.yml --event release --limit 5 --json databaseId,headBranch \
                     --jq "map(select(.headBranch == \"$TAG\"))[0].databaseId // empty" 2>/dev/null || true)
        [[ -n "$RUN_ID" ]] && break
        sleep 5
    done
    if [[ -z "$RUN_ID" ]]; then
        echo "    Could not find the workflow run, check the Actions tab of the repository" >&2
    elif gh run watch "$RUN_ID" --exit-status --interval 30 >/dev/null; then
        echo "    Linux builds attached"
    else
        echo "    The Linux builds failed: gh run view $RUN_ID --log-failed" >&2
        exit 1
    fi
fi
echo "==> Done: $(gh release view "$TAG" --json url --jq .url)"
gh release view "$TAG" --json assets --jq '.assets[].name' | sed 's/^/    /'
